import React from "react";
import type { SimilarTicketSummary } from "../../types/ticketTypes";
import "../TicketUpload/TicketUploadForm.css";

interface Props {
  suggestion: string;
  confidence: number;
  method: string;
  similarTickets: SimilarTicketSummary[];
}

const METHOD_INFO: Record<string, { icon: string; title: string; note?: string }> = {
  "ai-refined": {
    icon: "✨",
    title: "AI-Generated Resolution",
    note: "Written by AI using the resolutions of the similar tickets below.",
  },
  retrieval: {
    icon: "📚",
    title: "Recommended Resolution",
    note: "Taken from the most similar resolved tickets in the knowledge base.",
  },
  "ai-fallback": {
    icon: "🤖",
    title: "AI-Powered Guidance",
    note: "No similar historical tickets were found. This guidance was generated by AI from general IT support knowledge - please verify it.",
  },
  "no-match": {
    icon: "🔎",
    title: "No Similar Tickets Found",
    note: "Nothing similar exists in the knowledge base yet. Generic next steps are shown below.",
  },
};

/** Shows a suggested resolution, how it was produced, and the matching past tickets. */
const ResolutionResult: React.FC<Props> = ({
  suggestion,
  confidence,
  method,
  similarTickets,
}) => {
  const info = METHOD_INFO[method] ?? METHOD_INFO["retrieval"];
  const isNotice = method === "ai-fallback" || method === "no-match";

  return (
    <>
      <div className="resolution-section">
        <div className="resolution-header">
          <span className="resolution-icon">{info.icon}</span>
          <h4 className="resolution-title">{info.title}</h4>
          {similarTickets.length > 0 && (
            <span
              className="confidence-badge"
              title="Similarity between your description and the best matching resolved ticket"
            >
              {(confidence * 100).toFixed(0)}% match
            </span>
          )}
        </div>
        {info.note && (
          <p
            className={isNotice ? "ai-fallback-notice" : "resolution-note"}
            style={
              isNotice
                ? {
                    background: "#fef3c7",
                    border: "1px solid #fbbf24",
                    borderRadius: "8px",
                    padding: "12px",
                    color: "#92400e",
                    fontSize: "14px",
                  }
                : {
                    fontSize: "13px",
                    color: "rgba(255, 255, 255, 0.85)",
                    margin: "0 0 12px",
                  }
            }
          >
            {info.note}
          </p>
        )}
        <div className="resolution-content">
          <p className="resolution-text" style={{ whiteSpace: "pre-wrap" }}>
            {suggestion}
          </p>
        </div>
      </div>

      {similarTickets.length > 0 && (
        <>
          <div className="resolution-divider"></div>
          <div className="similar-tickets-section">
            <div className="similar-header">
              <span className="similar-icon">🔍</span>
              <h4 className="similar-title">Similar Resolved Tickets</h4>
              <span className="similar-count">{similarTickets.length}</span>
            </div>
            <div className="similar-tickets-list">
              {similarTickets.map((ticket, index) => (
                <div
                  key={ticket.ticket_id ?? index}
                  className="similar-ticket-card"
                >
                  <div className="similar-ticket-header">
                    <span className="similar-ticket-category">
                      {ticket.ticket_id ? `${ticket.ticket_id} · ` : ""}
                      {ticket.category}
                    </span>
                    <span className="similarity-score">
                      {(ticket.similarity_score * 100).toFixed(0)}% match
                    </span>
                  </div>
                  <p className="similar-ticket-description">
                    {ticket.description}
                  </p>
                  <div className="similar-ticket-resolution">
                    <strong>Resolution:</strong>
                    <p>{ticket.resolution}</p>
                  </div>
                </div>
              ))}
            </div>
          </div>
        </>
      )}
    </>
  );
};

export default ResolutionResult;
